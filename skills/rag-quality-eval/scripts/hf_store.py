"""Hugging Face dataset store for the RAG evaluation: source PDFs, cached index
snapshots and eval reports in one public dataset repo.

Layout of the repo (default ``cmboulanger/zotero-rag-gold``, override with
``--repo`` or ``$RAG_EVAL_HF_REPO``):

  README.md                                  dataset card (regenerated by ``card``)
  sources/<attachmentKey>.pdf + manifest.json  the gold library's open-access PDFs
  snapshots/<embedding-model>/latest.jsonl.gz  index snapshot (bin/library_snapshot.py)
  snapshots/<embedding-model>/latest.json      its provenance (extractor, commit, counts)
  reports/index.json                           one summary entry per published run
  reports/<run>/{report.md,report.json,meta.json,results.jsonl,judgments/,raw/}   the archive: every run, kept
  reports/latest/                              copy of the newest run (HF has no symlinks), replaced in the same commit

Why a snapshot rather than rebuilding: the index depends on the extractor
(Kreuzberg in production) which not every environment can run; the snapshot
restores the production-equivalent index anywhere with the same embedding model.

Commands (``python`` is enough for ``card``/``status``; the rest needs
``uv run python`` for ``huggingface_hub``):

  status                    what the repo currently holds
  init                      create the public dataset repo + first card (needs a write token)
  pull-sources              download sources/ into .local/rag_eval_hf/
  push-sources [DIR]        upload DIR (default .local/rag_eval_sources) to sources/
  pull-index [--model M]    download the snapshot for embedding model M (default: the running backend's)
  push-index FILE           upload a snapshot file as the model's ``latest`` (+ provenance)
  push-report RUN_DIR       upload a report (``--with-raw`` adds raw/ traces) and refresh the card
  pull-report NAME          download reports/NAME into data/logs/rag_eval/NAME (usable as --baseline)
  card                      regenerate README.md from the repo's own contents

Auth: a token from ``$HF_TOKEN``/``$HF_API_TOKEN``, or none where the environment's
proxy injects credentials (cloud sessions). Reading a public repo needs no token.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DEFAULT_URL, PROJECT_ROOT, http_json, load_gold  # noqa: E402

DEFAULT_REPO = "cmboulanger/zotero-rag-gold"
LOCAL_ROOT = PROJECT_ROOT / ".local" / "rag_eval_hf"
SOURCES_DIR = PROJECT_ROOT / ".local" / "rag_eval_sources"
RUNS_DIR = PROJECT_ROOT / "data" / "logs" / "rag_eval"
REPORT_FILES = ("report.md", "report.json", "meta.json", "results.jsonl")


# ---------------------------------------------------------------- pure helpers
def model_slug(model: str) -> str:
    """Directory-safe name of an embedding model."""
    return model.replace("/", "--").replace(" ", "_")


def snapshot_paths(model: str) -> tuple[str, str]:
    """(snapshot file, provenance file) paths inside the repo for an embedding model."""
    base = f"snapshots/{model_slug(model)}"
    return f"{base}/latest.jsonl.gz", f"{base}/latest.json"


def snapshot_header(path: Path) -> dict:
    """First line of a ``bin/library_snapshot.py`` file."""
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        return json.loads(fh.readline())


def git_commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=PROJECT_ROOT, capture_output=True, text=True)
        return out.stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def sources_fingerprint(manifest: dict) -> str:
    """Stable short hash of the source set, so a snapshot says which PDFs it was built from."""
    keys = sorted(f"{a['attachment_key']}:{a.get('sha256', '')}" for a in manifest.get("attachments", []))
    return hashlib.sha256("\n".join(keys).encode()).hexdigest()[:12]


def provenance(header: dict, extractor: str, preset: str, sources_sha: str) -> dict:
    """Provenance record stored next to a snapshot."""
    return {
        "embedding_model": header["embedding_model_name"], "embedding_dim": header["embedding_dim"],
        "library": header["slug"], "counts": header["counts"], "extractor": extractor, "preset": preset,
        "sources_fingerprint": sources_sha, "git_commit": git_commit(),
        "built_at": header.get("created_at"), "published_at": datetime.now(timezone.utc).isoformat(),
    }


def report_index_entry(name: str, report: dict) -> dict:
    """Compact summary of a run for ``reports/index.json`` and the card's table."""
    meta, groups = report.get("meta", {}), report.get("groups", {})
    return {
        "run": name,
        "gold_version": meta.get("gold_version"),
        "git_commit": meta.get("git_commit"),
        "started_at": meta.get("started_at") or meta.get("timestamp"),
        "groups": {
            g: {k: s.get(k) for k in ("runs", "composite", "recall_en", "recall_non_en", "judge_overall",
                                      "lost_in_retrieval", "lost_in_generation", "verdicts")}
            for g, s in groups.items()
        },
    }


def _fmt(v: Any) -> str:
    return "n/a" if v is None else f"{v:.2f}" if isinstance(v, float) else str(v)


def render_card(repo: str, manifest: Optional[dict], provs: list[dict], index: list[dict]) -> str:
    """Dataset card (README.md) built from the repo's own contents."""
    lines = [
        "---", "license: cc-by-4.0", "pretty_name: zotero-rag gold evaluation corpus",
        "tags: [rag, zotero, evaluation, retrieval, open-access]", "language: [en, de, fr, es]",
        "size_categories: [n<1K]", "---", "",
        "# zotero-rag gold evaluation corpus", "",
        "Source documents, a prebuilt vector index and published results for the `rag-quality-eval` skill of "
        "[zotero-rag](https://github.com/cboulanger/zotero-rag). The corpus is the public Zotero group "
        "[test-rag-plugin](https://www.zotero.org/groups/6297749/test-rag-plugin) (about reference management software).", "",
        "## Contents", "",
        "| Path | What |", "|---|---|",
        "| `sources/` | the group's open-access PDFs (`<attachmentKey>.pdf`) and `manifest.json` (item metadata) |",
        "| `snapshots/<embedding-model>/` | `latest.jsonl.gz`: chunks, vectors and index metadata exported with "
        "`bin/library_snapshot.py`; `latest.json`: how it was built |",
        "| `reports/` | one folder per published eval run, plus `index.json` |", "",
        "## License and attribution", "",
        "The PDFs are open-access publications licensed CC BY 4.0; copyright remains with their authors. "
        "`sources/manifest.json` lists title, authors, year and the Zotero item of each. The snapshot contains the "
        "documents' text as chunks and is therefore distributed under the same license. Gold questions live in the "
        "code repository (`skills/rag-quality-eval/gold/`).", "",
        "## Use", "",
        f"`uv run python skills/rag-quality-eval/scripts/gold_env.py up` restores the index from `{repo}` into a local "
        "backend; see `skills/rag-quality-eval/SKILL.md`.", "",
    ]
    if manifest:
        lines += [f"## Sources", "", f"{len(manifest.get('attachments', []))} PDFs, fingerprint "
                  f"`{sources_fingerprint(manifest)}`.", ""]
    if provs:
        lines += ["## Index snapshots", "",
                  "| Embedding model | Chunks | Extractor | Preset | Code commit | Built |", "|---|---|---|---|---|---|"]
        for p in provs:
            lines.append(f"| {p['embedding_model']} ({p['embedding_dim']}-dim) | {p['counts'].get('chunks')} | "
                         f"{p['extractor']} | {p['preset']} | `{p['git_commit']}` | {(p.get('built_at') or '')[:10]} |")
        lines.append("")
    if index:
        newest = max(index, key=lambda e: e["run"])["run"]
        lines += ["## Results", "",
                  f"Latest run: `{newest}` ([report](reports/latest/report.md)); every run is kept under `reports/<run>/`.", "",
                  "Composite is the mean over runs (0-1); recall is fact recall; judge is the 0-5 judged overall.", "",
                  "| Run | Gold | Commit | Preset / model | Runs | Composite | Recall en | Recall non-en | Judge | Lost retr. | Lost gen. |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for e in sorted(index, key=lambda e: e["run"], reverse=True)[:30]:
            for g, s in e["groups"].items():
                lines.append(f"| `{e['run']}` | v{_fmt(e.get('gold_version'))} | `{e.get('git_commit') or '?'}` | {g} | "
                             f"{s.get('runs')} | {_fmt(s.get('composite'))} | {_fmt(s.get('recall_en'))} | "
                             f"{_fmt(s.get('recall_non_en'))} | {_fmt(s.get('judge_overall'))} | "
                             f"{s.get('lost_in_retrieval')} | {s.get('lost_in_generation')} |")
        lines.append("")
    return "\n".join(lines)


def plan_report_commit(run_name: str, staged: list[str], existing: list[str]) -> tuple[list[tuple[str, str]], list[str]]:
    """Paths for one atomic report publication.

    ``staged`` are the run's files relative to its folder. Returns ``(adds, deletes)``:
    ``adds`` is ``(path_in_repo, relative_file)`` for the archive copy under
    ``reports/<run>/`` and the ``reports/latest/`` mirror; ``deletes`` removes files
    left in ``reports/latest/`` by the previous run that this one does not have,
    so ``latest`` never mixes two runs.
    """
    adds = [(f"reports/{run_name}/{rel}", rel) for rel in staged] + [(f"reports/latest/{rel}", rel) for rel in staged]
    keep = {f"reports/latest/{rel}" for rel in staged}
    deletes = [f for f in existing if f.startswith("reports/latest/") and f not in keep]
    return adds, deletes


def merge_index(index: list[dict], entry: dict) -> list[dict]:
    """Insert/replace the entry for a run (idempotent re-publish)."""
    return sorted([e for e in index if e["run"] != entry["run"]] + [entry], key=lambda e: e["run"])


# ---------------------------------------------------------------- HF access
def _api(token: Optional[str] = None):
    try:
        from huggingface_hub import HfApi
    except ImportError:
        raise SystemExit("[FAIL] huggingface_hub is missing: run with `uv run python` (uv sync).")
    return HfApi(token=token or os.environ.get("HF_TOKEN") or os.environ.get("HF_API_TOKEN") or None)


def _read_json(api, repo: str, path: str, default: Any) -> Any:
    from huggingface_hub import hf_hub_download
    try:
        local = hf_hub_download(repo, path, repo_type="dataset", token=api.token, local_dir=LOCAL_ROOT / "_cache")
    except Exception:  # missing file or empty repo: treat as absent
        return default
    return json.loads(Path(local).read_text(encoding="utf-8"))


def _list(api, repo: str) -> list[str]:
    try:
        return api.list_repo_files(repo, repo_type="dataset")
    except Exception:
        return []


def refresh_card(api, repo: str) -> None:
    files = _list(api, repo)
    manifest = _read_json(api, repo, "sources/manifest.json", None) if "sources/manifest.json" in files else None
    provs = [_read_json(api, repo, f, None) for f in files if f.startswith("snapshots/") and f.endswith("/latest.json")]
    index = _read_json(api, repo, "reports/index.json", []) if "reports/index.json" in files else []
    card = render_card(repo, manifest, [p for p in provs if p], index)
    api.upload_file(path_or_fileobj=card.encode(), path_in_repo="README.md", repo_id=repo, repo_type="dataset",
                    commit_message="Update dataset card")


# ---------------------------------------------------------------- commands
def cmd_status(a, api) -> int:
    files = _list(api, a.repo)
    if not files:
        print(f"[WARN] {a.repo} is empty or not reachable")
        return 1
    top: dict[str, int] = {}
    for f in files:
        top[f.split("/")[0]] = top.get(f.split("/")[0], 0) + 1
    print(f"{a.repo}: " + ", ".join(f"{k}: {n} files" for k, n in sorted(top.items())))
    for f in files:
        if f.endswith("/latest.json"):
            p = _read_json(api, a.repo, f, {})
            print(f"  snapshot {p.get('embedding_model')}: {p.get('counts')} chunks/dedup, {p.get('extractor')}, "
                  f"commit {p.get('git_commit')}, built {str(p.get('built_at'))[:10]}")
    return 0


def cmd_init(a, api) -> int:
    api.create_repo(a.repo, repo_type="dataset", private=False, exist_ok=True)
    refresh_card(api, a.repo)
    print(f"[OK] https://huggingface.co/datasets/{a.repo}")
    return 0


def cmd_pull_sources(a, api) -> int:
    from huggingface_hub import snapshot_download
    snapshot_download(a.repo, repo_type="dataset", allow_patterns=["sources/*"], local_dir=LOCAL_ROOT, token=api.token)
    print(LOCAL_ROOT / "sources")
    return 0


def cmd_push_sources(a, api) -> int:
    src = Path(a.dir)
    if not (src / "manifest.json").exists():
        raise SystemExit(f"[FAIL] {src}/manifest.json missing: run `gold_env.py fetch-sources` first")
    api.create_repo(a.repo, repo_type="dataset", exist_ok=True)
    api.upload_folder(folder_path=str(src), path_in_repo="sources", repo_id=a.repo, repo_type="dataset",
                      allow_patterns=["*.pdf", "manifest.json"], commit_message="Update source PDFs")
    refresh_card(api, a.repo)
    print(f"[OK] pushed sources from {src}")
    return 0


def _backend_model(url: str) -> str:
    status, data = http_json("GET", f"{url}/api/migration/embedding-info", timeout=20)
    if status != 200 or not isinstance(data, dict):
        raise SystemExit(f"[FAIL] cannot read the embedding model from {url} (HTTP {status}); pass --model")
    return data["embedding_model_name"]


def cmd_pull_index(a, api) -> int:
    from huggingface_hub import hf_hub_download
    model = a.model or _backend_model(a.url)
    snap, prov = snapshot_paths(model)
    local = hf_hub_download(a.repo, snap, repo_type="dataset", token=api.token, local_dir=LOCAL_ROOT, revision=a.revision)
    hf_hub_download(a.repo, prov, repo_type="dataset", token=api.token, local_dir=LOCAL_ROOT, revision=a.revision)
    print(local)
    return 0


def cmd_push_index(a, api) -> int:
    path = Path(a.file)
    header = snapshot_header(path)
    manifest = json.loads((Path(a.sources) / "manifest.json").read_text()) if (Path(a.sources) / "manifest.json").exists() else {}
    prov = provenance(header, a.extractor, a.preset, sources_fingerprint(manifest))
    snap, prov_path = snapshot_paths(header["embedding_model_name"])
    api.create_repo(a.repo, repo_type="dataset", exist_ok=True)
    api.upload_file(path_or_fileobj=str(path), path_in_repo=snap, repo_id=a.repo, repo_type="dataset",
                    commit_message=f"Index snapshot for {header['embedding_model_name']} ({a.extractor})")
    api.upload_file(path_or_fileobj=json.dumps(prov, indent=2).encode(), path_in_repo=prov_path, repo_id=a.repo,
                    repo_type="dataset", commit_message="Snapshot provenance")
    refresh_card(api, a.repo)
    print(f"[OK] pushed {snap}")
    return 0


def cmd_push_report(a, api) -> int:
    run = Path(a.run_dir).resolve()
    if not (run / "report.json").exists():
        raise SystemExit(f"[FAIL] {run}/report.json missing: run report.py first")
    meta = json.loads((run / "meta.json").read_text()) if (run / "meta.json").exists() else {}
    if not meta.get("gold_version"):
        meta["gold_version"] = load_gold().get("version")
    meta.setdefault("git_commit", git_commit())
    report = json.loads((run / "report.json").read_text())
    report["meta"] = {**report.get("meta", {}), **meta}
    api.create_repo(a.repo, repo_type="dataset", exist_ok=True)
    from huggingface_hub import CommitOperationAdd, CommitOperationDelete
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp)
        for name in REPORT_FILES:
            if (run / name).exists():
                (stage / name).write_bytes((run / name).read_bytes())
        (stage / "report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
        for sub in ("judgments",) + (("raw",) if a.with_raw else ()):
            if (run / sub).is_dir():
                for f in (run / sub).rglob("*"):
                    if f.is_file():
                        (stage / sub / f.relative_to(run / sub)).parent.mkdir(parents=True, exist_ok=True)
                        (stage / sub / f.relative_to(run / sub)).write_bytes(f.read_bytes())
        rels = sorted(str(f.relative_to(stage)) for f in stage.rglob("*") if f.is_file())
        adds, deletes = plan_report_commit(run.name, rels, _list(api, a.repo))
        # One commit: the archive copy and the `latest` mirror change together.
        api.create_commit(
            a.repo, repo_type="dataset",
            operations=[CommitOperationAdd(dest, str(stage / rel)) for dest, rel in adds]
            + [CommitOperationDelete(d) for d in deletes],
            commit_message=f"Eval run {run.name} (archive + latest)",
        )
    index = merge_index(_read_json(api, a.repo, "reports/index.json", []), report_index_entry(run.name, report))
    api.upload_file(path_or_fileobj=json.dumps(index, indent=2).encode(), path_in_repo="reports/index.json",
                    repo_id=a.repo, repo_type="dataset", commit_message="Update report index")
    refresh_card(api, a.repo)
    print(f"[OK] archived at reports/{run.name}/ and mirrored to reports/latest/: "
          f"https://huggingface.co/datasets/{a.repo}/tree/main/reports/{run.name}")
    return 0


def cmd_pull_report(a, api) -> int:
    from huggingface_hub import snapshot_download
    name = a.name
    if name == "latest":
        index = _read_json(api, a.repo, "reports/index.json", [])
        if not index:
            raise SystemExit("[FAIL] no published reports")
        name = index[-1]["run"]
    snapshot_download(a.repo, repo_type="dataset", allow_patterns=[f"reports/{name}/*"], local_dir=LOCAL_ROOT, token=api.token)
    dest = RUNS_DIR / name
    dest.mkdir(parents=True, exist_ok=True)
    for f in (LOCAL_ROOT / "reports" / name).rglob("*"):
        if f.is_file():
            (dest / f.relative_to(LOCAL_ROOT / "reports" / name)).parent.mkdir(parents=True, exist_ok=True)
            (dest / f.relative_to(LOCAL_ROOT / "reports" / name)).write_bytes(f.read_bytes())
    print(dest)
    return 0


def cmd_card(a, api) -> int:
    refresh_card(api, a.repo)
    print(f"[OK] card updated: https://huggingface.co/datasets/{a.repo}")
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--repo", default=os.environ.get("RAG_EVAL_HF_REPO", DEFAULT_REPO))
    p.add_argument("--url", default=DEFAULT_URL, help="backend used to find the embedding model")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status"); sub.add_parser("init"); sub.add_parser("pull-sources"); sub.add_parser("card")
    s = sub.add_parser("push-sources"); s.add_argument("dir", nargs="?", default=str(SOURCES_DIR))
    s = sub.add_parser("pull-index"); s.add_argument("--model"); s.add_argument("--revision")
    s = sub.add_parser("push-index"); s.add_argument("file")
    s.add_argument("--extractor", default=os.environ.get("EXTRACTOR_BACKEND", "kreuzberg"))
    s.add_argument("--preset", default=os.environ.get("MODEL_PRESET", "remote-kisski"))
    s.add_argument("--sources", default=str(SOURCES_DIR), help="dir holding manifest.json (for the fingerprint)")
    s = sub.add_parser("push-report"); s.add_argument("run_dir"); s.add_argument("--with-raw", action="store_true")
    s = sub.add_parser("pull-report"); s.add_argument("name", help="run folder name or 'latest'")
    a = p.parse_args(argv)
    api = _api()
    return globals()["cmd_" + a.cmd.replace("-", "_")](a, api)


if __name__ == "__main__":
    sys.exit(main())
